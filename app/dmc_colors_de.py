def get_color_info(dmc_number: str) -> tuple:
    """
    Get color name and hex code for DMC number

    Args:
        dmc_number: DMC number as string

    Returns:
        Tuple of (color_name, hex_code) or ("", "") if not found
    """
    return DMC_COLORS_DE.get(str(dmc_number).upper(), ("", ""))


def get_color_name(dmc_number: str) -> str:
    """
    Get the color name for a DMC number

    Args:
        dmc_number: DMC number as string

    Returns:
        Color name or empty string if not found
    """
    color_info = get_color_info(dmc_number)
    return color_info[0]


def get_hex_code(dmc_number: str) -> str:
    """
    Get the hex color code for a DMC number

    Args:
        dmc_number: DMC number as string

    Returns:
        Hex color code or empty string if not found
    """
    color_info = get_color_info(dmc_number)
    return color_info[1]


def search_colors(query: str) -> dict:
    """
    Search for DMC colors by number or name

    Args:
        query: Search query (DMC number or color name)

    Returns:
        Dictionary of matching DMC numbers with (color_name, hex_code) tuples
    """
    query_lower = query.lower()
    results = {}

    for dmc_num, (color_name, hex_code) in DMC_COLORS_DE.items():
        if query_lower in dmc_num.lower() or query_lower in color_name.lower():
            results[dmc_num] = {"name": color_name, "hex": hex_code}

    return results


def get_all_colors() -> dict:
    """
    Get all DMC colors

    Returns:
        Dictionary of all DMC numbers with (color_name, hex_code) tuples
    """
    return {dmc: {"name": name, "hex": hex_code}
            for dmc, (name, hex_code) in DMC_COLORS_DE.items()}
